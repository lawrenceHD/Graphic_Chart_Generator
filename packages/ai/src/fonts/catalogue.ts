import { z } from 'zod';
import raw from './catalogue.json' with { type: 'json' };

const score = z.number().int().min(0).max(100);

export const FontFamilySchema = z
  .object({
    family: z.string().min(1).max(80),
    category: z.enum(['Sans Serif', 'Serif', 'Display', 'Handwriting', 'Monospace']),
    classes: z.record(z.string(), score),
    expressive: z.record(z.string(), score),
    quality: score,
    popularity: z.number().int().positive(),
    weights: z.array(z.number().int().min(1).max(1000)),
    italic: z.boolean(),
    variable: z.boolean(),
  })
  .strict();
export type FontFamily = z.infer<typeof FontFamilySchema>;

const CatalogueSchema = z
  .object({ source: z.string(), families: z.array(FontFamilySchema).min(1) })
  .strict();

let cache: FontFamily[] | undefined;

// Open-source Google Fonts only (generated by tools/references/fonts.py), validated once.
export function loadFontCatalogue(): FontFamily[] {
  cache ??= CatalogueSchema.parse(raw).families;
  return cache;
}
